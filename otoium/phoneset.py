def cons_units(c):
    if c in _CU:
        return list(_CU[c])
    if c.endswith("y") and c[:-1] in _CU:
        return cons_units(c[:-1]) + ["gl_y"]
    if c.endswith("w") and c[:-1] in _CU:
        return cons_units(c[:-1]) + ["gl_w"]
    raise KeyError(f"未対応の子音: {c}")


def mora_units(cons, vowel):
    return ["NN"] if vowel == "N" else cons_units(cons) + [vowel]


def is_burst(unit):
    return unit.startswith("br")


